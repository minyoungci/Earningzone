const { chromium } = require('../.ds-sync/node_modules/playwright')
const fs = require('fs')
const path = require('path')
const base = process.env.TOSSBOT_TEST_URL || 'http://127.0.0.1:8765'
const out = process.env.TOSSBOT_TEST_OUTPUT || path.resolve(__dirname, '../.tmp/public_docs_20261006')
const assert = (ok, message) => { if (!ok) throw new Error(message) }

async function main() {
  fs.mkdirSync(out, { recursive: true })
  const browser = await chromium.launch({ headless: true, channel: 'msedge' })
  const results = []
  try {
    for (const width of [1440, 390, 320]) {
      const context = await browser.newContext({ viewport: { width, height: 1000 }, reducedMotion: 'reduce' })
      const errors = [], writes = []
      await context.route('**/*', route => {
        if (route.request().method() !== 'GET') writes.push(route.request().url())
        return route.request().url().startsWith(base) ? route.continue() : route.abort()
      })
      const page = await context.newPage()
      page.on('pageerror', e => errors.push(e.message))
      page.on('console', m => { if (m.type() === 'error' && !m.text().includes('ERR_FAILED')) errors.push(m.text()) })
      const noOverflow = async () => assert(!await page.evaluate(() => document.documentElement.scrollWidth > innerWidth+1), `overflow ${width} ${page.url()}`)
      await page.goto(base+'/symbol/005930',{waitUntil:'networkidle'})
      await page.getByRole('heading',{name:'차트 분석 도구',exact:true}).waitFor()
      await page.getByText(/완성 추정 200\/200봉/).waitFor()
      assert(await page.locator('canvas').count()>0,'Missing chart')
      await page.getByLabel('시작 가격',{exact:true}).fill('100')
      await page.getByLabel('끝 가격',{exact:true}).fill('200')
      await page.getByLabel('시작 봉',{exact:true}).selectOption('0')
      await page.getByLabel('끝 봉',{exact:true}).selectOption('10')
      await page.getByLabel('측정 상단',{exact:true}).fill('120')
      await page.getByLabel('측정 하단 / 넥라인',{exact:true}).fill('100')
      await page.getByLabel('돌파 / 이탈 가격',{exact:true}).fill('122')
      assert((await page.locator('.study-scenario').innerText()).includes('142'),'Measured target example failed')
      await page.getByLabel('현재 도구의 선 표시',{exact:true}).check()
      await page.getByRole('button',{name:'예상 변동폭',exact:true}).click()
      await page.getByLabel('기준 가격',{exact:true}).fill('100')
      await page.getByLabel('연율 IV',{exact:false}).fill('20')
      await page.getByLabel('남은 기간',{exact:false}).fill('365')
      assert((await page.locator('.study-scenario').innerText()).includes('80 ~ 120'),'EM formula failed')
      await page.getByRole('button',{name:'위험 · 수량',exact:true}).click()
      for (const [label,value] of Object.entries({'진입 가격':'100','손절 가격':'90','목표 가격':'120','계좌 자산 · 원':'10000','위험 비율 · %':'1','매수 예산 · 원':'10000','가용 현금 · 원':'10000','환율 · 원/종목 통화':'1'})) await page.getByLabel(label,{exact:true}).fill(value)
      assert((await page.locator('.study-scenario').innerText()).includes('10주'),'Risk quantity failed')
      assert((await page.locator('.study-scenario').innerText()).includes('2 : 1'),'Net RR failed')
      await noOverflow()
      await page.screenshot({path:path.join(out,`chart-${width}.png`),fullPage:true})
      await page.getByLabel('피벗 가격',{exact:true}).selectOption('body')
      await page.getByLabel('좌·우 확인 봉',{exact:true}).selectOption('5')
      await page.getByLabel('이동평균',{exact:true}).selectOption('SMA')
      await page.getByLabel('50',{exact:true}).check()
      await page.getByLabel('시간 단위',{exact:true}).selectOption('1m')
      await page.getByText('실현 변동성 · 분봉당',{exact:true}).waitFor()
      assert(!await page.getByLabel('현재 도구의 선 표시',{exact:true}).isChecked(),'Timeframe change kept stale scenario drawing')
      await page.goto(base+'/learn',{waitUntil:'networkidle'})
      await page.getByRole('heading',{name:'분석 시스템과 알고리즘',level:1,exact:true}).waitFor()
      assert(await page.locator('.study-method').count()===8,'Methods missing')
      await page.getByText('공개 문서 6',{exact:true}).waitFor()
      const library = await (await context.request.get(base+'/api/financial/library')).json()
      assert(library.visibility==='public' && library.counts.sources===0 && library.counts.images===0 && library.documents.length===6,'Private library metadata exposed')
      for (const d of library.documents) {
        await page.locator('.study-doc-nav').getByRole('button',{name:d.title,exact:true}).click()
        await page.locator('.financial-markdown').getByRole('heading',{name:d.title,exact:true}).waitFor()
        await noOverflow()
      }
      await page.locator('.study-doc-nav').getByRole('button',{name:'분석 시스템과 알고리즘',exact:true}).click()
      await page.locator('.financial-markdown').getByRole('heading',{name:'분석 시스템과 알고리즘',exact:true}).waitFor()
      await page.locator('.financial-markdown').getByRole('link').first().click()
      await page.waitForFunction(()=>location.search.includes('doc=ANALYSIS_PIPELINE'))
      await page.getByLabel('문서 검색 · 제목 / 본문',{exact:true}).fill('no-such-term-12345')
      await page.getByText('검색 결과가 없습니다.',{exact:true}).waitFor()
      await page.getByLabel('문서 검색 · 제목 / 본문',{exact:true}).fill('리테스트')
      await page.waitForFunction(()=>document.querySelectorAll('.study-doc-nav button').length>0)
      assert(await page.locator('.study-gallery img').count()===0,'Private gallery exposed')
      for (const resource of ['documents/01_CHART_STUDY','documents/source_inventory','images/private.png']) {
        assert((await context.request.get(base+'/api/financial/'+resource)).status()===404,'Private resource accessible')
      }
      await noOverflow()
      await page.screenshot({path:path.join(out,`library-${width}.png`),fullPage:true})
      await page.locator('.settings-menu > summary').click()
      await page.getByRole('button',{name:'다크',exact:true}).click()
      await page.waitForFunction(()=>document.documentElement.dataset.theme==='wallet')
      await page.locator('.settings-menu > summary').click()
      await noOverflow()
      assert(errors.length===0,JSON.stringify(errors)); assert(writes.length===0,'Analysis issued write requests')
      results.push({width,chartTools:true,geometry:true,em:true,risk:true,timeframe:true,publicDocuments:6,search:true,privateResourcesBlocked:true,theme:true,noWrites:true})
      await context.close()
    }
    fs.writeFileSync(path.join(out,'financial-browser-results.json'),JSON.stringify(results,null,2))
    console.log(JSON.stringify({passed:true,widths:results.length,errors:0,writes:0}))
  } finally { await browser.close() }
}
main().catch(e=>{console.error(e);process.exitCode=1})
